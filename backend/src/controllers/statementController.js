/**
 * STATEMENT CONTROLLER — generate and stream a PDF of the user's
 * transaction history for a date window. Uses PDFKit.
 */
const mongoose = require('mongoose');
const PDFDocument = require('pdfkit');
const Account = require('../models/Account');
const Transaction = require('../models/Transaction');

const fmt = (n) => `₹${Number(n).toLocaleString('en-IN', { minimumFractionDigits: 2 })}`;
const fmtDate = (d) => new Date(d).toLocaleString('en-IN', { dateStyle: 'medium', timeStyle: 'short' });

exports.download = async (req, res, next) => {
  try {
    const uid = new mongoose.Types.ObjectId(req.user._id);
    const to = req.query.to ? new Date(req.query.to) : new Date();
    const from = req.query.from ? new Date(req.query.from) : new Date(Date.now() - 30 * 86400_000);

    const account = await Account.findOne({ userId: uid });
    if (!account) return res.status(404).json({ ok: false, error: { code: 'NOT_FOUND', message: 'No account' } });

    const txns = await Transaction.find({
      $or: [{ fromUserId: uid }, { toUserId: uid }],
      status: 'COMPLETED',
      createdAt: { $gte: from, $lte: to },
    }).sort({ createdAt: 1 });

    // Stream the PDF straight to the response.
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="sanchiva-statement-${Date.now()}.pdf"`);

    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    doc.pipe(res);

    // --- Header ---
    doc.fontSize(26).fillColor('#0ea5e9').text('SANCHIVA', 50, 50);
    doc.fontSize(10).fillColor('#64748b').text('Next-Gen Fintech & Banking', 50, 80);
    doc.fontSize(16).fillColor('#0f172a').text('Account Statement', 50, 110);
    doc
      .fontSize(10)
      .fillColor('#475569')
      .text(`Account Holder: ${req.user.name}`, 50, 135)
      .text(`Account Number: ${account.accountNumber}`, 50, 150)
      .text(`Period: ${fmtDate(from)} — ${fmtDate(to)}`, 50, 165)
      .text(`Currency: ${account.currency}`, 50, 180);

    doc.moveTo(50, 200).lineTo(545, 200).strokeColor('#cbd5e1').lineWidth(1).stroke();

    // --- Transactions table ---
    let y = 220;
    doc.font('Helvetica-Bold').fontSize(9).fillColor('#64748b');
    doc.text('DATE', 50, y);
    doc.text('DESCRIPTION', 130, y);
    doc.text('TYPE', 330, y);
    doc.text('AMOUNT', 460, y, { width: 85, align: 'right' });
    y += 16;
    doc.moveTo(50, y - 6).lineTo(545, y - 6).strokeColor('#e2e8f0').lineWidth(0.5).stroke();

    doc.font('Helvetica').fontSize(9).fillColor('#0f172a');
    let running = 0;
    for (const t of txns) {
      if (y > 760) {
        doc.addPage();
        y = 50;
      }
      const isIn = t.toUserId && t.toUserId.equals(uid);
      const amt = isIn ? t.amount : -t.amount;
      running += amt;
      doc.text(fmtDate(t.createdAt), 50, y, { width: 75 });
      doc.text(t.description.slice(0, 38), 130, y, { width: 195 });
      doc.text(t.type, 330, y);
      doc.fillColor(amt >= 0 ? '#059669' : '#dc2626').text(fmt(amt), 460, y, {
        width: 85,
        align: 'right',
      });
      doc.fillColor('#0f172a');
      y += 16;
    }

    doc.moveTo(50, y + 4).lineTo(545, y + 4).strokeColor('#cbd5e1').lineWidth(1).stroke();
    y += 18;
    doc.font('Helvetica-Bold').text('Closing Balance', 330, y);
    doc.text(fmt(account.balance), 460, y, { width: 85, align: 'right' });

    doc.fontSize(8).fillColor('#94a3b8').text(
      'This statement is system-generated by Sanchiva. For discrepancies, contact support@sanchiva.com.',
      50,
      800,
      { width: 495, align: 'center' }
    );

    doc.end();
  } catch (err) {
    next(err);
  }
};
